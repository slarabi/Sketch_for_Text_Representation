# 1. Generation and Calculation Functions
# =====================================================================
def generate_single_sketch(query_text):
    model_gray_coco.eval()
    with torch.no_grad():
        q_emb = sbert.encode(query_text, convert_to_tensor=True).unsqueeze(0).to(DEVICE)
        _, sketch_tensor, _ = model_gray_coco(q_emb)
        sketch_np = (sketch_tensor.squeeze(0).squeeze(0).cpu().numpy() * 255).astype(np.uint8)
    img_pil = Image.fromarray(sketch_np).convert("RGB")
    return img_pil.resize((W_SKETCH, H_SKETCH), Image.Resampling.BILINEAR)

def compare_texts_and_sketches(text1, text2):
    model_gray_coco.eval()
    texts = [text1, text2]

    with torch.no_grad():
        # Encoding Raw SBERT
        sbert_embs = sbert.encode(texts, convert_to_tensor=True, device=DEVICE)
        sbert_embs_norm = F.normalize(sbert_embs, dim=1)
        sim_sbert = torch.sum(sbert_embs_norm[0] * sbert_embs_norm[1]).item()

        # Semantic Latent Space Similarity
        latent_embs = model_gray_coco.semantic_encoder(sbert_embs)
        latent_embs_norm = F.normalize(latent_embs, dim=1)
        sim_latent = torch.sum(latent_embs_norm[0] * latent_embs_norm[1]).item()

        # Generation of sketches and encoding via sketch_encoder
        z = model_gray_coco.semantic_encoder(sbert_embs)
        sketches = model_gray_coco.sketch_decoder(z)
        sketch_latents = model_gray_coco.sketch_encoder(sketches)
        sketch_latents_norm = F.normalize(sketch_latents, dim=1)
        sim_sketch = torch.sum(sketch_latents_norm[0] * sketch_latents_norm[1]).item()

    img1 = Image.fromarray((sketches[0].squeeze(0).cpu().numpy() * 255).astype(np.uint8)).convert("RGB")
    img2 = Image.fromarray((sketches[1].squeeze(0).cpu().numpy() * 255).astype(np.uint8)).convert("RGB")

    return sim_sbert, sim_latent, sim_sketch, img1, img2


