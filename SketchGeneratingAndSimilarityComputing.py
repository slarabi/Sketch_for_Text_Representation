# Loading SBERT
print("Loading SBERT...")
sbert = SentenceTransformer("all-MiniLM-L6-v2", device=str(DEVICE))

# Definition of Architecture
class SemanticEncoder(nn.Module):
    def __init__(self, input_dim=384, latent_dim=384):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(input_dim, 384), nn.ReLU(), nn.Dropout(0.1),
            nn.Linear(384, latent_dim), nn.LayerNorm(latent_dim),
        )
    def forward(self, x):
        return self.net(x)

class GraySketchDecoder(nn.Module):
    def __init__(self, latent_dim=384):
        super().__init__()
        self.fc = nn.Linear(latent_dim, 128 * 13 * 25)
        self.deconv = nn.Sequential(
            nn.BatchNorm2d(128), nn.ReLU(),
            nn.Upsample(scale_factor=2, mode="bilinear", align_corners=False),
            nn.Conv2d(128, 64, kernel_size=3, padding=1), nn.BatchNorm2d(64), nn.ReLU(),
            nn.Upsample(scale_factor=2, mode="bilinear", align_corners=False),
            nn.Conv2d(64, 32, kernel_size=3, padding=1), nn.BatchNorm2d(32), nn.ReLU(),
            nn.Upsample(scale_factor=2, mode="bilinear", align_corners=False),
            nn.Conv2d(32, C_SKETCH, kernel_size=3, padding=1),
            nn.Upsample(size=(H_SKETCH, W_SKETCH), mode="bilinear", align_corners=False),
            nn.Sigmoid(),
        )
    def forward(self, z):
        return self.deconv(self.fc(z).view(-1, 128, 13, 25))

class GraySketchEncoder(nn.Module):
    def __init__(self, output_dim=384):
        super().__init__()
        self.conv = nn.Sequential(
            nn.Conv2d(C_SKETCH, 32, 4, 2, 1), nn.ReLU(),
            nn.Conv2d(32, 64, 4, 2, 1), nn.ReLU(),
            nn.Conv2d(64, 128, 4, 2, 1), nn.ReLU(),
            nn.AdaptiveAvgPool2d((4, 8)),
            nn.Flatten(),
        )
        self.fc = nn.Linear(128 * 4 * 8, output_dim)
    def forward(self, sketch):
        return self.fc(self.conv(sketch))

class EndToEndGrayPipeline(nn.Module):
    def __init__(self, input_dim=384, latent_dim=384):
        super().__init__()
        self.semantic_encoder = SemanticEncoder(input_dim, latent_dim)
        self.sketch_decoder = GraySketchDecoder(latent_dim)
        self.sketch_encoder = GraySketchEncoder(latent_dim)
    def forward(self, text_emb):
        z = self.semantic_encoder(text_emb)
        sketch = self.sketch_decoder(z)
        return z, sketch, self.sketch_encoder(sketch)

# Instantiation and loading of weights
model_gray_coco = EndToEndGrayPipeline(input_dim=384, latent_dim=384).to(DEVICE)

if os.path.exists(model_path):
    print(f"Loading model from: {model_path}")
    model_gray_coco.load_state_dict(torch.load(model_path, map_location=DEVICE))
    model_gray_coco.eval()
    print("Model ready !")
else:
    raise FileNotFoundError(f"Model not found at: {model_path}. Please check the path or configure CUSTOM_MODEL_PATH.")


